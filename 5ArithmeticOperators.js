//Arithmetic operators

//    +.-.*./,%,**,--,++  
//**  - to get power value - exponential

var a =50
var b =30
console.log(a+b)
console.log(a-b)
console.log(a*b)
console.log(a/b)
console.log(a%b)
console.log(a**b)
console.log(b++) //30 -current value 
console.log(b)   //-current value =31
console.log(++b) //32 [31+1]
console.log(a--) //50
console.log(a)   //current value =49
console.log(--a) //48

